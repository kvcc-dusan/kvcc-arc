// Parses registry/foundation.css and registry/motion-tokens.ts into kvcc/tokens/tokens.json and kvcc/tokens/TOKENS.md.
// Run: node kvcc/scripts/extract-tokens.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const strip = s => s.replace(/\/\*[\s\S]*?\*\//g, "");
const css = strip(readFileSync(path.join(root, "registry/foundation.css"), "utf8"));

function parseBlocks(src, prefix = "") {
  const out = [];
  let i = 0;
  while (i < src.length) {
    const open = src.indexOf("{", i);
    if (open === -1) break;
    const selector = src.slice(i, open).trim();
    let depth = 1, j = open + 1;
    while (j < src.length && depth) { if (src[j] === "{") depth++; else if (src[j] === "}") depth--; j++; }
    const body = src.slice(open + 1, j - 1);
    if (selector.startsWith("@supports")) out.push(...parseBlocks(body, "@supports relative-color "));
    else out.push({ selector: prefix + selector, body });
    i = j;
  }
  return out;
}

const scopes = {};
for (const { selector, body } of parseBlocks(css)) {
  const decls = {};
  for (const d of body.split(";")) {
    const k = d.indexOf(":");
    if (k < 0) continue;
    const name = d.slice(0, k).trim();
    if (!name.startsWith("--")) continue;
    decls[name] = d.slice(k + 1).trim().replace(/\s+/g, " ");
  }
  if (Object.keys(decls).length) scopes[selector] = { ...(scopes[selector] ?? {}), ...decls };
}

const base = scopes[":root"];
const dark = scopes[':root[data-theme="dark"]'];
const accents = {};
for (const [sel, v] of Object.entries(scopes)) {
  let m = sel.match(/^:root\[data-accent="(\w+)"\]$/);
  if (m) { (accents[m[1]] ??= {}).light = { ...(accents[m[1]].light ?? {}), ...v }; continue; }
  m = sel.match(/^:root\[data-theme="dark"\]\[data-accent="(\w+)"\]$/);
  if (m) (accents[m[1]] ??= {}).dark = { ...(accents[m[1]].dark ?? {}), ...v };
}
const relativeSeries = Object.fromEntries(Object.entries(scopes).filter(([s]) => s.startsWith("@supports")));

const motionSrc = strip(readFileSync(path.join(root, "registry/motion-tokens.ts"), "utf8"))
  .replace("export const motionTokens =", "return").replace(/\s+as const;?\s*$/, "");
const motion = new Function(motionSrc)();

mkdirSync(path.join(root, "kvcc/tokens"), { recursive: true });
writeFileSync(path.join(root, "kvcc/tokens/tokens.json"), JSON.stringify({
  source: "registry/foundation.css, registry/motion-tokens.ts (upstream: kuratlielia/arc-library, MIT)",
  themeAttribute: 'data-theme="dark" on <html>', accentAttribute: 'data-accent on <html>',
  base, dark, accents, relativeSeries, motion,
}, null, 2) + "\n");

const roles = {
  "--background": "Page behind everything", "--surface": "Cards, inputs, panels", "--surface-raised": "Menus, popovers, dialogs",
  "--surface-muted": "Hover states, wells, code", "--foreground": "Primary text and icons", "--text-secondary": "Supporting text",
  "--text-muted": "Hints, placeholders, metadata", "--border": "Default 1px separators", "--border-subtle": "Dividers inside a surface",
  "--border-strong": "Hovered or pressed edges", "--accent": "Selected nav, progress, emphasis", "--accent-strong": "Accent text and pressed accent",
  "--accent-subtle": "Accent tint fill", "--accent-foreground": "Text on accent fill",
  "--success": "Healthy or complete, with a label", "--warning": "Needs attention soon, with a label", "--danger": "Destructive or error, with a label",
};
const md = [];
const table = (head, rows) => { md.push(`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`, ...rows.map(r => `| ${r.join(" | ")} |`), ""); };
const code = v => "`" + String(v).replace(/\|/g, "\\|") + "`";
md.push("# Tokens", "", "Generated by `kvcc/scripts/extract-tokens.mjs` from `registry/foundation.css` and `registry/motion-tokens.ts`. Do not edit by hand.", "",
  "Theme: `data-theme=\"dark\"` on `<html>` (light is the default). Accent: `data-accent` on `<html>`, one of: " + Object.keys(accents).map(code).join(", ") + ".", "",
  "## Semantic color roles", "");
table(["Token", "Use", "Light", "Dark"], Object.entries(roles).map(([k, use]) => [code(k), use, code(base[k] ?? "-"), code(dark[k] ?? base[k] ?? "-")]));
md.push("## Neutral ramp (do not use directly in product code)", "");
table(["Token", "Value"], Object.entries(base).filter(([k]) => k.startsWith("--neutral-")).map(([k, v]) => [code(k), code(v)]));
md.push("## Shape", "");
table(["Token", "Value"], Object.entries(base).filter(([k]) => /^--(radius|control-height)/.test(k)).map(([k, v]) => [code(k), code(v)]));
md.push("## Spacing (4px grid)", "");
table(["Token", "Value"], Object.entries(base).filter(([k]) => k.startsWith("--space-")).map(([k, v]) => [code(k), code(v)]));
md.push("## Type", "");
table(["Token", "Value"], Object.entries(base).filter(([k]) => /^--(font|text|tracking|leading)/.test(k) && !/^--text-(secondary|muted)$/.test(k)).map(([k, v]) => [code(k), code(v)]));
md.push("## Elevation", "");
table(["Token", "Light", "Dark"], Object.keys(base).filter(k => k.startsWith("--shadow-")).map(k => [code(k), code(base[k]), code(dark[k] ?? "-")]));
md.push("## Motion (CSS)", "");
table(["Token", "Value"], Object.entries(base).filter(([k]) => /^--(ease|duration)/.test(k)).map(([k, v]) => [code(k), code(v.length > 70 ? v.slice(0, 67) + "..." : v)]));
md.push("## Motion presets (`lib/motion-tokens.ts`)", "", "```json", JSON.stringify(motion, null, 2), "```", "");
md.push("## Selection controls", "");
table(["Token", "Light", "Dark"], Object.keys(base).filter(k => k.startsWith("--control-") && !k.startsWith("--control-height")).map(k => [code(k), code(base[k]), code(dark[k] ?? "-")]));
md.push("## Accents", "");
table(["Accent", "Light accent", "Light strong", "Dark accent", "Dark strong", "Light control-on", "Dark control-on"],
  Object.entries(accents).map(([n, a]) => [code(n), code(a.light["--accent"]), code(a.light["--accent-strong"]), code(a.dark["--accent"]), code(a.dark["--accent-strong"]), code(a.light["--control-on"] ?? "-"), code(a.dark["--control-on"] ?? "-")]));
md.push("## Brand gradient (marketing backdrops only)", "");
table(["Token", "Light", "Dark"], Object.keys(base).filter(k => k.startsWith("--arc-gradient")).map(k => [code(k), code(base[k]), code(dark[k] ?? "-")]));
md.push("## Chart series", "", "`--series-1` to `--series-4` derive from the active accent via relative color (fallback hex values below). Override on any element to rebrand a chart.", "");
table(["Token", "Light fallback", "Dark fallback"], [1, 2, 3, 4].map(n => [code(`--series-${n}`), code(base[`--series-${n}`]), code(dark[`--series-${n}`])]));
md.push("## Focus", "", "Pointer focus draws no ring. Keyboard focus (`:focus-visible`) draws one shared accent outline from `foundation.css`. Tune with `--focus-outline`, `--focus-outline-width` (2px), `--focus-outline-offset` (2px). Never write per-component outlines or box-shadow rings.", "");
writeFileSync(path.join(root, "kvcc/tokens/TOKENS.md"), md.join("\n"));
console.log("base tokens:", Object.keys(base).length, "| dark overrides:", Object.keys(dark).length, "| accents:", Object.keys(accents).join(","), "| series scopes:", Object.keys(relativeSeries).length);
