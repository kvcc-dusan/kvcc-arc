// Builds kvcc/COMPONENTS.md and kvcc/components.json from registry.json. Run: node kvcc/scripts/build-index.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const reg = JSON.parse(readFileSync(path.join(root, "registry.json"), "utf8"));
const items = reg.items.map(i => ({
  id: i.name, title: i.title, kind: i.meta?.kind ?? i.type, tier: i.meta?.tier ?? "free",
  categories: i.categories ?? [], description: i.description, dependencies: i.dependencies ?? [],
  registryDependencies: (i.registryDependencies ?? []).map(d => d.split("/").pop().replace(/\.json$/, "")),
  docs: i.meta?.docs ?? null, markdown: i.meta?.markdown ?? null,
}));
writeFileSync(path.join(root, "kvcc/components.json"), JSON.stringify(items, null, 2) + "\n");

const by = k => items.filter(i => i.kind === k);
const md = ["# Component index", "", "Generated by `kvcc/scripts/build-index.mjs` from `registry.json`. Do not edit by hand.", "",
  `Items: ${items.length} (${by("component").length} components, ${by("block").length} blocks, ${items.length - by("component").length - by("block").length} support). Tiers: ${[...new Set(items.map(i => i.tier))].join(", ")}.`, ""];
for (const kind of ["component", "block"]) {
  md.push(`## ${kind === "component" ? "Components" : "Blocks"}`, "");
  const cats = [...new Set(by(kind).flatMap(i => i.categories.slice(0, 1)))];
  for (const c of cats) {
    md.push(`### ${c}`, "", "| Id | Description | Needs |", "|---|---|---|");
    for (const i of by(kind).filter(i => i.categories[0] === c))
      md.push(`| \`${i.id}\` | ${i.description.replace(/\|/g, "\\|")} | ${[...i.dependencies, ...i.registryDependencies.filter(d => d !== "arc-motion-tokens")].join(", ") || "-"} |`);
    md.push("");
  }
}
md.push("## Support", "", ...items.filter(i => !["component", "block"].includes(i.kind)).map(i => `- \`${i.id}\`: ${i.description}`), "");
writeFileSync(path.join(root, "kvcc/COMPONENTS.md"), md.join("\n"));
console.log("items:", items.length, "| components:", by("component").length, "| blocks:", by("block").length, "| tiers:", [...new Set(items.map(i => i.tier))].join(","));
